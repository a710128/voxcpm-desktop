use std::path::PathBuf;

fn ensure_default_icon() {
    // `tauri::generate_context!()` expects an icon at `icons/icon.png` by default.
    // Keep the repo unblocked in dev by generating a tiny placeholder if missing.
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let icons_dir = manifest_dir.join("icons");
    let icon_path = icons_dir.join("icon.png");

    if icon_path.exists() {
        return;
    }

    let _ = std::fs::create_dir_all(&icons_dir);

    // 1x1 transparent PNG.
    // Generated once and written into the src-tauri tree so the proc-macro can read it.
    const PNG_1X1: &[u8] = &[
        0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44,
        0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0x1F,
        0x15, 0xC4, 0x89, 0x00, 0x00, 0x00, 0x0A, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x63, 0x00,
        0x01, 0x00, 0x00, 0x05, 0x00, 0x01, 0x0D, 0x0A, 0x2D, 0xB4, 0x00, 0x00, 0x00, 0x00, 0x49,
        0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82,
    ];

    let _ = std::fs::write(icon_path, PNG_1X1);
}

fn main() {
    ensure_default_icon();
    tauri_build::build()
}
